// Office Open Source v0.0.8 — build script
// profiles: --profile=universal (ES5 app.js + WASM & asm.js OCR) | legacy (ES5 + asm.js OCR only: Android 6.0-7.1)
//           | modern (ES2017 app.js + WASM OCR only: Android 8+, Windows 7-11 with Chrome/Edge 109+)   --out=<dir>
// 1) generate icon subset  2) esbuild bundle (ESM -> IIFE)  3) Babel -> ES5 for Chrome 44 WebView (Android 6.0)
// 4) minify  5) CSS -> postcss (custom-properties fallback + autoprefixer)  6) copy vendor libs into dist/
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const NM = fs.existsSync(path.join(ROOT, 'node_modules')) ? path.join(ROOT, 'node_modules') : path.resolve(__dirname, '../../../v005/deps/node_modules');
const esbuild = (() => {
  try { const e = require('esbuild'); e.transformSync(''); return e; } catch (_) {}
  try { const e = require(path.join(NM, 'esbuild')); e.transformSync(''); return e; } catch (_) {}
  try { return require('/opt/npm-tools/node_modules/esbuild'); } catch (_) {}
  throw new Error('esbuild not found in node_modules or system');
})();
const babel = require('@babel/core');
const postcss = require('postcss');
const ARG = k => { const a = process.argv.find(x => x.indexOf('--' + k + '=') === 0); return a ? a.split('=')[1] : null; };
const PROFILE = ARG('profile') || 'universal';
const DIST = ARG('out') ? path.resolve(ARG('out')) : path.join(ROOT, 'dist');
const MODERN = PROFILE === 'modern';
const WANT_WASM = PROFILE !== 'legacy', WANT_ASM = PROFILE !== 'modern';
const DEV = process.argv.includes('--dev');
// v0.1.8: tên + phiên bản lấy từ src/core/util.js (không ghi cứng)
const UTIL = fs.readFileSync(path.join(ROOT, 'src/core/util.js'), 'utf8');
const APP_VER = (/export const VERSION = '([^']+)'/.exec(UTIL) || [])[1] || '0.0.0';
const APP_NAME = (/export const APP_NAME = '([^']+)'/.exec(UTIL) || [])[1] || 'Yomi-Office Open Source';
const TARGETS = { chrome: '44', android: '4.4' };

function rmrf(p) { if (fs.existsSync(p)) fs.rmSync(p, { recursive: true, force: true }); }
function mkdirp(p) { fs.mkdirSync(p, { recursive: true }); }
function copy(src, dst) { mkdirp(path.dirname(dst)); fs.copyFileSync(src, dst); fs.chmodSync(dst, 0o644); }
function walk(dir, out) { out = out || []; for (const f of fs.readdirSync(dir)) { const p = path.join(dir, f); if (fs.statSync(p).isDirectory()) walk(p, out); else out.push(p); } return out; }

function genIcons() {
  const all = JSON.parse(fs.readFileSync(path.join(__dirname, 'lucide.json'), 'utf8').replace(/^\uFEFF/, ''));
  const used = new Set(['file', 'x', 'check', 'chevron-down', 'chevron-right', 'chevron-left', 'chevron-up', 'circle-help']);
  const re = /(?:ic|icon)\(\s*['"]([a-z0-9-]+)['"]|icon:\s*['"]([a-z0-9-]+)['"]|data-ic=["']([a-z0-9-]+)["']/g;
  for (const f of walk(path.join(ROOT, 'src'))) {
    if (!f.endsWith('.js') || f.endsWith('icons.gen.js')) continue;
    const s = fs.readFileSync(f, 'utf8'); let m;
    while ((m = re.exec(s))) used.add(m[1] || m[2] || m[3]);
  }
  const out = {}; const missing = [];
  for (const n of used) { if (all[n]) out[n] = all[n]; else missing.push(n); }
  if (missing.length) console.warn('[icons] missing:', missing.join(', '));
  fs.writeFileSync(path.join(ROOT, 'src/core/icons.gen.js'), '// generated by tools/build.js (Lucide, ISC license)\nexport default ' + JSON.stringify(out) + ';\n');
  return Object.keys(out).length;
}

async function buildJs() {
  // esbuild targets Chrome 44 (Android 6.0 WebView): keeps ES2015 syntax Chrome 44 supports,
  // lowers async/await to generators + exponentiation; library gaps covered by src/core/polyfills.js
  // Per-file Babel (fast; whole-bundle Babel is quadratic): Chrome 44 = stock Android 6.0 WebView lacks arrows(45), spread(46),
  // classes/destructuring/default params(49), async(55). Generators (39+) and template literals (41+) stay native.
  const cacheDir = path.join(ROOT, '.babelcache'); if (!fs.existsSync(cacheDir)) fs.mkdirSync(cacheDir);
  const crypto = require('crypto'); let nb = 0, nc = 0; const t0 = Date.now();
  const es5 = { name: 'chrome44', setup(b) { b.onLoad({ filter: /\.m?js$/ }, async args => {
    const src = fs.readFileSync(args.path, 'utf8');
    const key = crypto.createHash('md5').update(src).digest('hex'); const cf = path.join(cacheDir, key + '.js');
    if (fs.existsSync(cf)) { nc++; return { contents: fs.readFileSync(cf, 'utf8'), loader: 'js' }; }
    const r2 = await babel.transformAsync(src, { babelrc: false, configFile: false, sourceType: 'module', compact: false, comments: false, filename: args.path,
      presets: [[require.resolve('@babel/preset-env'), { targets: { chrome: '44' }, modules: false, exclude: ['transform-regenerator'] }]] });
    fs.writeFileSync(cf, r2.code); nb++; return { contents: r2.code, loader: 'js' };
  }); } };
  const r = await esbuild.build({
    entryPoints: [path.join(ROOT, 'src/main.js')], bundle: true, format: 'iife', write: false, plugins: DEV || MODERN ? [] : [es5],
    target: DEV ? ['es2015'] : MODERN ? ['chrome61', 'edge79'] : ['es5'], supported: DEV || MODERN ? {} : { 'generator': true, 'template-literal': true, 'for-of': true, 'arrow': false, 'const-and-let': false, 'class': false, 'destructuring': false, 'default-argument': false, 'rest-argument': false, 'object-extensions': true, 'async-await': false },
    loader: { '.bas': 'text', '.txt': 'text' }, charset: 'utf8', legalComments: 'none', logLevel: 'warning', minify: !DEV, nodePaths: [NM],
    define: { 'process.env.NODE_ENV': '"production"', __VERSION__: '"0.1.7"', __PROFILE__: JSON.stringify(PROFILE) }, inject: [path.join(ROOT, 'src/core/polyfills.js')]
  });
  let out = r.outputFiles[0].text;
  if (!DEV && !MODERN) console.log('[es5] babel per-file: ' + nb + ' transformed, ' + nc + ' cached, ' + (Date.now() - t0) + 'ms');
  fs.writeFileSync(path.join(DIST, 'app.js'), '/*! ' + APP_NAME + ' v' + APP_VER + ' (' + PROFILE + ') | (c) ' + APP_NAME + ' contributors | bundled libs: see licenses.txt */\n' + out);
  return out.length;
}

async function buildCss() {
  const files = fs.readdirSync(path.join(ROOT, 'styles')).filter(f => f.endsWith('.css')).sort();
  let css = files.map(f => fs.readFileSync(path.join(ROOT, 'styles', f), 'utf8')).join('\n');
  const tpl = fs.readFileSync(path.join(ROOT, 'styles/accent.tpl'), 'utf8');
  for (const [k, c] of [['word', '#185abd'], ['excel', '#107c41'], ['ppt', '#c43e1c'], ['pdf', '#d83b01'], ['mathtype', '#68217a']]) css += '\n' + tpl.replace(/\{K\}/g, k).replace(/\{C\}/g, c);
  const res = await postcss([
    require('postcss-custom-properties')({ preserve: true }),
    require('autoprefixer')({ overrideBrowserslist: ['chrome >= 44', 'android >= 4.4'] })
  ]).process(css, { from: undefined });
  const min = (await esbuild.transform(res.css, { loader: 'css', minify: !DEV, target: 'chrome44' })).code;
  fs.writeFileSync(path.join(DIST, 'app.css'), min);
  return min.length;
}

async function vendor() {
  const V = path.join(DIST, 'vendor');
  copy(path.join(NM, 'jszip/dist/jszip.min.js'), path.join(V, 'jszip.min.js'));
  copy(path.join(NM, 'pdf-lib/dist/pdf-lib.min.js'), path.join(V, 'pdf-lib.min.js'));
  // v0.1.6: fontkit + DejaVu Sans for Unicode (Vietnamese) text drawn into PDFs
  const PF = path.join(ROOT, 'vendor_extra/pdffont');
  if (fs.existsSync(path.join(PF, 'package/dist/fontkit.umd.min.js'))) copy(path.join(PF, 'package/dist/fontkit.umd.min.js'), path.join(V, 'pdffont/fontkit.umd.min.js'));
  for (const f of ['DejaVuSans.ttf', 'DejaVuSans-Bold.ttf']) { const c = walk(PF).find(p => path.basename(p) === f); if (c) copy(c, path.join(V, 'pdffont', f)); }
  copy(path.join(NM, 'pdfjs-dist/es5/build/pdf.min.js'), path.join(V, 'pdfjs/pdf.min.js'));
  if (WANT_ASM) ['tesseract.min.js', 'worker.min.js', 'worker-compat.js', 'tesseract-core.asm.js'].forEach(f => copy(path.join(ROOT, 'vendor_extra/tesseract-asm', f), path.join(V, 'tesseract-asm', f)));
  copy(path.join(NM, 'pdfjs-dist/es5/build/pdf.worker.min.js'), path.join(V, 'pdfjs/pdf.worker.min.js'));
  // KaTeX: transpile to ES5 for old WebViews
  const k = fs.readFileSync(path.join(NM, 'katex/dist/katex.min.js'), 'utf8');
  const kb = await babel.transformAsync(k, { babelrc: false, configFile: false, compact: true, sourceType: 'script', presets: [[require.resolve('@babel/preset-env'), { targets: TARGETS, modules: false }]] });
  const kmin = (await esbuild.transform(kb.code, { minify: true, target: 'es5', supported: { 'arrow': false, 'const-and-let': false, 'class': false, 'template-literal': false } })).code;
  mkdirp(path.join(V, 'katex/fonts'));
  fs.writeFileSync(path.join(V, 'katex/katex.min.js'), kmin);
  let kcss = fs.readFileSync(path.join(NM, 'katex/dist/katex.min.css'), 'utf8');
  // keep only woff2 sources (smaller); Chrome 36+ supports woff2
  kcss = kcss.replace(/src:url\(([^)]+\.woff2)\) format\("woff2"\)(,url\([^)]+\) format\("[a-z]+"\))*/g, 'src:url($1) format("woff2")');
  fs.writeFileSync(path.join(V, 'katex/katex.min.css'), kcss);
  for (const f of fs.readdirSync(path.join(NM, 'katex/dist/fonts'))) if (f.endsWith('.woff2')) copy(path.join(NM, 'katex/dist/fonts', f), path.join(V, 'katex/fonts', f));
  // Tesseract (WASM OCR) — used on Windows / modern WebViews; Android 6 uses native OCR bridge
  if (WANT_WASM) { copy(path.join(NM, 'tesseract.js/dist/tesseract.min.js'), path.join(V, 'tesseract/tesseract.min.js'));
  copy(path.join(NM, 'tesseract.js/dist/worker.min.js'), path.join(V, 'tesseract/worker.min.js'));
  for (const f of ['tesseract-core-lstm.wasm.js', 'tesseract-core-simd-lstm.wasm.js']) copy(path.join(NM, 'tesseract.js-core', f), path.join(V, 'tesseract/core', f)); }
  for (const l of ['vie', 'eng']) copy(path.join(ROOT, 'tessdata', l + '.traineddata'), path.join(V, 'tesseract/lang', l + '.traineddata'));
  fs.writeFileSync(path.join(DIST, 'licenses.txt'), [
    APP_NAME + ' v' + APP_VER + ' bundles the following open-source components:',
    '- pdf.js 2.6.347 (Apache-2.0) https://github.com/mozilla/pdf.js',
    '- pdf-lib 1.17.1 (MIT) https://github.com/Hopding/pdf-lib',
    '- JSZip 3.10.1 (MIT or GPLv3, used under MIT) https://github.com/Stuk/jszip',
    '- KaTeX 0.16.11 (MIT) https://github.com/KaTeX/KaTeX',
    '- Tesseract.js 5.1.1 / tesseract.js-core (Apache-2.0) https://github.com/naptha/tesseract.js',
    '- tessdata_fast vie/eng (Apache-2.0) https://github.com/tesseract-ocr/tessdata_fast',
    '- Formula.js 4.4.9 (MIT) https://github.com/formulajs/formulajs — reference/implementation for Excel functions',
    '- jStat (MIT), bessel (Apache-2.0) via Formula.js',
    '- QR Code generator by Project Nayuki (MIT) https://github.com/nayuki/QR-Code-generator (ported)',
    '- Lucide icons (ISC) https://lucide.dev',
    '- sRGB-v2-micro.icc from Compact-ICC-Profiles (CC0 1.0) https://github.com/saucecontrol/Compact-ICC-Profiles — PDF/A output intent',
    '- core-js (MIT), regenerator-runtime (MIT)', ''
  ].join('\n'));
}

function statics() {
  for (const f of walk(path.join(ROOT, 'static'))) copy(f, path.join(DIST, path.relative(path.join(ROOT, 'static'), f)));
}

(async () => {
  const t0 = Date.now();
  const onlyApp = process.argv.includes('--app');
  fs.writeFileSync(path.join(ROOT, 'src/core/profile.gen.js'), '// generated by tools/build.js\nexport default ' + JSON.stringify({ profile: PROFILE, wasm: WANT_WASM, asm: WANT_ASM, version: '0.1.1' }) + ';\n');
  if (!onlyApp) { rmrf(DIST); }
  mkdirp(DIST);
  const n = genIcons();
  const js = await buildJs();
  const css = await buildCss();
  statics();
  if (!onlyApp || !fs.existsSync(path.join(DIST, 'vendor'))) await vendor();
  console.log(`build ok: icons=${n} app.js=${(js / 1024).toFixed(0)}KB app.css=${(css / 1024).toFixed(0)}KB in ${Date.now() - t0}ms`);
})().catch(e => { console.error(e); process.exit(1); });
